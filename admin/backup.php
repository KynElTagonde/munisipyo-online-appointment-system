<?php
/**
 * Database Backup Script
 * Generates and downloads a complete SQL dump of the 2-table schema and current data.
 */
require_once '../config.php';

// Authentication Guard - only logged-in Admin can export DB
requireAdmin();

$pdo = getDbConnection();

// Set download headers for .sql file
$filename = "munisipyo_db_backup_" . date("Y-m-d_His") . ".sql";
header("Content-Type: application/sql");
header("Content-Disposition: attachment; filename=\"{$filename}\"");
header("Cache-Control: no-cache, no-store, must-revalidate");
header("Pragma: no-cache");
header("Expires: 0");

$tables = ['users', 'appointments'];

echo "-- ==========================================================\n";
echo "-- Munisipyo Online Appointment System - Database Backup\n";
echo "-- Generated by Admin: " . $_SESSION['admin_user'] . "\n";
echo "-- Date: " . date('Y-m-d H:i:s') . "\n";
echo "-- Host: " . DB_HOST . " | Database: " . DB_NAME . "\n";
echo "-- ==========================================================\n\n";

echo "SET FOREIGN_KEY_CHECKS=0;\n";
echo "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n";
echo "SET time_zone = '+00:00';\n\n";

foreach ($tables as $table) {
    echo "-- --------------------------------------------------------\n";
    echo "-- Table structure for table `{$table}`\n";
    echo "-- --------------------------------------------------------\n";
    echo "DROP TABLE IF EXISTS `{$table}`;\n";

    // Fetch Create Table SQL
    $createStmt = $pdo->query("SHOW CREATE TABLE `{$table}`");
    $createRow = $createStmt->fetch(PDO::FETCH_NUM);
    echo $createRow[1] . ";\n\n";

    // Fetch Table Data
    $dataStmt = $pdo->query("SELECT * FROM `{$table}`");
    $rows = $dataStmt->fetchAll(PDO::FETCH_ASSOC);

    if (count($rows) > 0) {
        echo "-- Dumping data for table `{$table}`\n";
        
        $columnNames = array_keys($rows[0]);
        $columnsList = "`" . implode("`, `", $columnNames) . "`";

        foreach ($rows as $row) {
            $values = [];
            foreach ($row as $val) {
                if ($val === null) {
                    $values[] = "NULL";
                } else {
                    $values[] = $pdo->quote($val);
                }
            }
            echo "INSERT INTO `{$table}` ({$columnsList}) VALUES (" . implode(", ", $values) . ");\n";
        }
        echo "\n";
    }
}

echo "SET FOREIGN_KEY_CHECKS=1;\n";
echo "-- Backup completed successfully.\n";
exit;
?>
